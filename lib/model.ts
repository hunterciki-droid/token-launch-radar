// Token Radar's model: one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol that records no token AND is not a wrapped, staked,
// bridged or exchange product of a token that already trades — the watchlist's own
// exclusion rule, applied to the whole snapshot, not just its 40-row floor. That is
// 198 protocols here. The 144 pre-token records the rule leaves out (centralised
// exchanges, bridges, liquid-staking wrappers, versioned pools) are named in the
// dashboard's method note, never ranked as launches of their own.
//
// Implied value follows only from the snapshot's own figures, the same function for
// every protocol — no name is ever special-cased:
//
//   implied = tvl_usd x categoryMultiple x growthMult x maturityMult x chainMult
//
//   categoryMultiple  a stated FDV/TVL multiple per sector: capital managers and
//                     RWA command more per TVL dollar than plain infra, because
//                     their token would price the assets they manage, not the pipes.
//                     Applied uniformly from the category string alone.
//   growthMult        1 + clamp(change_7d, -50, +100) / 100 x 0.6. A protocol
//                     growing fast is worth more than a shrinking one of equal size.
//   maturityMult      0.7 + 0.3 x min(age_days, 1460) / 1460. A protocol that has run
//                     for years with no token has had longer to build the user base a
//                     launch would price; unknown age counts as 365 days.
//   chainMult         1 + 0.02 x min(chains - 1, 10). More chains, wider distribution.
//
// The live-token protocols are kept apart: the dashboard shows the top 24 by market
// cap with the market's own values, never mixed into the ranking.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

